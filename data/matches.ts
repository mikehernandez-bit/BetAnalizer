export const matches = rawMatches.reduce<Match[]>((acc, match) => {
  const normHome = normalizeTeamId(match.homeTeamId);
  const normAway = normalizeTeamId(match.awayTeamId);
  const key = `${match.date}-${normHome}-vs-${normAway}`;
  const keyInverse = `${match.date}-${normAway}-vs-${normHome}`;

  const existingIndex = acc.findIndex((m) => {
    if (m.date !== match.date) return false;
    const mHome = normalizeTeamId(m.homeTeamId);
    const mAway = normalizeTeamId(m.awayTeamId);
    const mKey = `${m.date}-${mHome}-vs-${mAway}`;
    return mKey === key || mKey === keyInverse;
  });

  if (existingIndex >= 0) {
    // Si el partido actual es BUILT_IN (comienza con real-), reemplaza al borrador anterior
    if (match.id.startsWith("real-")) {
      acc[existingIndex] = match;
    }
  } else {
    acc.push(match);
  }
  return acc;
}, []);

/**
 * Un partido se considera vencido (expirado) cuando han transcurrido 2 horas o más (>= 120 min)
 * desde su hora de inicio programada. Por ejemplo:
 * - Inicio: 11:00 -> A partir de las 13:00 ya NO se muestra en el sistema.
 * - Inicio: 12:30 -> A partir de las 14:30 ya NO se muestra en el sistema.
 */
export function isMatchExpired(match: Match, customNow?: Date): boolean {
  if (!match || !match.date || !match.time) return false;
  if (match.status === "finished" || (match.status as string) === "cancelled") return true;

  const [year, month, day] = match.date.split("-").map(Number);
  const [hours, minutes] = match.time.split(":").map(Number);

  if (isNaN(year) || isNaN(month) || isNaN(day) || isNaN(hours) || isNaN(minutes)) {
    return false;
  }

  const startMs = new Date(year, month - 1, day, hours, minutes, 0, 0).getTime();
  const expirationMs = startMs + 2 * 60 * 60 * 1000;

  let nowMs: number;
  if (customNow) {
    nowMs = customNow.getTime();
  } else {
    const parts = new Intl.DateTimeFormat("en-US", {
      timeZone: "America/Lima",
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      hour12: false,
    }).formatToParts(new Date());

    const values = Object.fromEntries(parts.map((p) => [p.type, p.value]));
    const h = Number(values.hour) % 24;
    const nowLocalDate = new Date(
      Number(values.year),
      Number(values.month) - 1,
      Number(values.day),
      h,
      Number(values.minute),
      0,
      0
    );
    nowMs = nowLocalDate.getTime();
  }

  return nowMs >= expirationMs;
}

/**
 * Para auditoría predictiva y tickets, el límite es el saque inicial, no las
 * dos horas de cortesía visual que usa isMatchExpired para ocultar partidos.
 */
export function hasMatchStarted(match: Match, customNow = new Date()): boolean {
  if (!match?.date || !match?.time) return false;
  if (match.status === "live" || match.status === "finished") return true;
  const kickoff = new Date(`${match.date}T${match.time}:00-05:00`);
  return Number.isFinite(kickoff.getTime()) && customNow.getTime() >= kickoff.getTime();
}

export function getMatchById(id: string): Match | undefined {
  return matches.find((m) => m.id === id);
}

export function getMatchesByTeam(teamId: string): Match[] {
  return matches.filter((m) => m.homeTeamId === teamId || m.awayTeamId === teamId);
}

export function getMatchesByCompetition(competitionId: string): Match[] {
  return matches.filter((m) => m.competitionId === competitionId);
}

export function getUpcomingMatches(customNow?: Date): Match[] {
  return matches
    .filter((m) => (m.status === "scheduled" || m.status === "live") && !isMatchExpired(m, customNow))
    .sort((a, b) => {
      if (a.status !== b.status) return a.status === "live" ? -1 : 1;
      return a.date + a.time < b.date + b.time ? -1 : 1;
    });
}

export function getFinishedMatches(): Match[] {
  return matches.filter((m) => m.status === "finished" || isMatchExpired(m));
}

export function getMatchesOnDate(dateIso: string): Match[] {
  return matches.filter((m) => {
    if (m.date !== dateIso) return false;
    if (isMatchExpired(m)) return false;
    return true;
  });
}
